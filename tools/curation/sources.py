#!/usr/bin/env python3
"""Provenance ledger for the audio corpus.

The licence gate (`licence.py`) answers "may this file be used at all?". It does
not answer the two questions that decide whether a *particular* file is usable:
where it came from, and which of its reuse conditions has actually been checked.

This module builds and audits `docs/curation/audio-sources.json`, the versioned
record of every audio file in the corpus. The masters themselves stay outside git
(`~/projects/birdie-curation`, ~75 MB); the ledger is the part that must not be
lost, because a file whose source page, recordist and licence cannot be named is
not usable no matter what its licence string says.

    python3 tools/curation/sources.py --write   # rebuild the ledger from the manifests
    python3 tools/curation/sources.py --check   # audit ledger + files, nonzero on failure
    python3 tools/curation/sources.py --report  # per-file status and what is still needed
    python3 tools/curation/sources.py --table   # the markdown table embedded in the doc

Three states, and only three:

    ready    the licence is permitted and every field needed to use the file
             (recordist, source page, licence version or PD basis, digest) is
             recorded and verified
    blocked  the licence *family* is permitted but a field is missing, so the
             file cannot be used until someone does one named thing
    refused  the licence is not permitted, or is unknown, or the archive publishes
             no mapping for it; not usable on any terms short of written permission

Exit codes: 0 everything consistent, 1 at least one audit failure.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from licence import classify  # noqa: E402  (same directory, stdlib-only module)

REPO = Path(__file__).resolve().parents[2]
LEDGER = REPO / "docs" / "curation" / "audio-sources.json"
DOC = REPO / "docs" / "curation" / "american-robin-audio.md"
SPECIES_CHECKS = REPO / "docs" / "curation" / "species-checks.json"
DEFAULT_CORPUS = Path.home() / "projects" / "birdie-curation" / "american-robin"

TABLE_BEGIN = "<!-- BEGIN SOURCES TABLE (generated by tools/curation/sources.py --table) -->"
TABLE_END = "<!-- END SOURCES TABLE -->"

# Macaulay publishes a licence *class*, never a version. Only the codes whose
# meaning is documented are mapped; the rest fail closed. See
# docs/curation/american-robin-audio.md and the audio-corpus-curation skill.
MACAULAY = {
    "LICENSE10": ("cc0", "CC0", "Macaulay licence code LICENSE10 = CC0"),
    "LICENSE5": ("cc-by", "CC BY", None),  # class known, version never published
    "LICENSE8": ("cc-by-nc", "CC BY-NC", "Macaulay licence code LICENSE8 = CC BY-NC"),
}

PD_BASIS = {
    "File:American Robin Yellowstone National Park.ogg":
        "work of the US National Park Service (US federal government, public domain)",
    "File:American Robin.ogg":
        "released into the public domain by the recordist on the Commons file page",
    "File:Yellowstone sound library - American Robin - 001.mp3":
        "NPS & MSU Acoustic Atlas recording, published as public domain",
}


def sh(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def digests(path: Path) -> tuple[str, str, int]:
    sha1, sha256 = hashlib.sha1(), hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            sha1.update(chunk)
            sha256.update(chunk)
    return sha1.hexdigest(), sha256.hexdigest(), path.stat().st_size


def species_checks() -> dict:
    """Recorded BirdNET verdicts, keyed by file id; empty when none was run yet."""
    if not SPECIES_CHECKS.exists():
        return {}
    return json.loads(SPECIES_CHECKS.read_text()).get("checks", {})


def duration(path: Path) -> float | None:
    try:
        out = sh("ffprobe", "-v", "error", "-show_entries", "format=duration",
                 "-of", "default=nw=1:nk=1", str(path))
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None
    try:
        return round(float(out.strip()), 2)
    except ValueError:
        return None


def slug(text: str) -> str:
    s = text.lower()
    s = s.replace("file:", "")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s


def recording_key(title: str) -> str:
    m = re.search(r"XC(\d+)", title)
    if m:
        return "xc" + m.group(1)
    return slug(title)


def classify_entry(licence: str, url: str) -> tuple[bool, str | None, str]:
    v = classify(licence, url)
    return v.allowed, v.licence, v.reason


def family_of(canonical: str | None) -> str | None:
    """cc-by-sa-4.0 -> cc-by-sa; cc0 and public-domain are their own family."""
    if not canonical:
        return None
    m = re.match(r"^(.*)-\d\.\d$", canonical)
    return m.group(1) if m else canonical


# Macaulay's tag vocabulary includes workflow markers as well as vocalisation
# types. Only these describe what the file is; `no_playback`, `archive` and
# friends must never be read as a type.
MACAULAY_TYPE_TAGS = {
    "song": "song",
    "dawn_song": "song",
    "whisper_song": "song",
    "call": "call",
    "flight_call": "call",
    "alarm_call": "call",
}


def macaulay_label(tags: list[str] | None) -> dict | None:
    if not tags:
        return None
    kinds = sorted({MACAULAY_TYPE_TAGS[t] for t in tags if t in MACAULAY_TYPE_TAGS})
    if not kinds:
        return None
    return {
        "verdict": ", ".join(kinds),
        "asPublished": list(tags),
        "basis": "archive-tag",
        "source": "Macaulay asset tags",
    }


def commons_label(xc_type: str | None, carried_by: str | None = None) -> dict | None:
    """The recordist's own `Type:` field, normalised to song and/or call."""
    if not xc_type:
        return None
    text = " ".join(xc_type.lower().replace(",", " ").split())
    kinds = [k for k in ("song", "call") if k in text]
    if not kinds:
        return None
    return {
        "verdict": ", ".join(kinds),
        "asPublished": xc_type,
        "basis": "recordist-type",
        "source": "Commons extmetadata Type field" + (f" on {carried_by}" if carried_by else ""),
    }



def build(corpus: Path) -> dict:
    commons_manifest = json.loads((corpus / "manifest.json").read_text())
    macaulay_manifest = json.loads((corpus / "macaulay" / "manifest.json").read_text())
    audition = json.loads((corpus / "audition-index.json").read_text())

    audition_ids = {e["local"]: e["auditionId"] for e in audition if e.get("auditionId")}
    used_ids: set[str] = set()

    # Some XC recordings are mirrored twice: the audition .ogg and a later .mp3
    # whose Commons description carries the recordist's `Type:` field. The label
    # belongs to the recording, not the file, so a sibling can carry it for both.
    commons_labels: dict[str, tuple[str, str]] = {}
    for e in commons_manifest["files"]:
        if e.get("xcType"):
            commons_labels.setdefault(recording_key(e["title"]), (e["xcType"], e["title"]))

    def unique(base: str) -> str:
        candidate, n = base, 2
        while candidate in used_ids:
            candidate = f"{base}-{n}"
            n += 1
        used_ids.add(candidate)
        return candidate

    entries: list[dict] = []

    for e in commons_manifest["files"]:
        path = Path(e["local"])
        sha1, sha256, size = digests(path)
        aid = audition_ids.get(e["local"])
        entry_id = unique(aid.lower() if aid else slug(path.stem))
        allowed, canonical, reason = classify_entry(e["license"], e.get("licenseUrl", ""))
        needs: list[str] = []
        recordist = (e.get("recordist") or "").strip()
        if not recordist or recordist == "?":
            recordist = None
            needs.append(
                "name the recordist: the file metadata has no recordist; the uploader is "
                "Mdf and the template is {{Self|GFDL|Cc-by-sa-3.0-migrated}}, so either find "
                "the original Xeno-canto recordist or credit \"Mdf (Wikimedia Commons)\""
            )
        basis = PD_BASIS.get(e["title"]) if canonical == "public-domain" else None
        if canonical == "public-domain" and not basis:
            needs.append("record the public-domain basis from the file page")
        label_type = commons_labels.get(recording_key(e["title"]))
        label = commons_label(label_type[0], label_type[1]) if label_type else None
        if label is None:
            needs.append(
                "record the song/call label: neither this file nor another mirror of the "
                "same recording carries the recordist's Type: field, so a song or call "
                "claim has nothing to cite"
            )
        if e.get("sha1") and sha1 != e["sha1"]:
            needs.append("local file does not match the published SHA1 — re-download")
        if not e.get("sourceUrl"):
            needs.append("record the source page URL")
        licence_obj = {
            "asPublished": e["license"],
            "id": canonical,
            "family": family_of(canonical),
            "deed": e.get("licenseUrl") or None,
            "versionVerified": (None if canonical == "public-domain"
                                else bool(re.search(r"\d\.\d", e.get("licenseUrl", "")))),
            "howVerified": (
                basis if canonical == "public-domain"
                else "versioned deed URL in the Commons file metadata"
                if re.search(r"\d\.\d", e.get("licenseUrl", ""))
                else None
            ),
        }
        entries.append({
            "id": entry_id,
            "auditionId": aid,
            "recordingId": recording_key(e["title"]),
            "library": "Wikimedia Commons" + (" (Xeno-canto mirror)" if "XC" in e["title"] else ""),
            "title": e["title"],
            "sourceUrl": e.get("sourceUrl"),
            "fileUrl": e.get("fileUrl"),
            "recordist": recordist,
            "label": label,
            "licence": licence_obj,
            "status": "refused" if not allowed else ("blocked" if needs else "ready"),
            "reason": None if allowed else reason,
            "verification": {
                "sha1": sha1,
                "sha1MatchesPublished": sha1 == e.get("sha1"),
                "sha256": sha256,
                "hashBasis": "published SHA1 matched",
                "checkedOn": "2026-11-23",
                "needs": needs,
            },
            "storage": {
                "master": str(path.relative_to(corpus)),
                "bytes": size,
                "durationSeconds": e.get("durationSeconds") or duration(path),
            },
        })

    for group in ("files", "rejected"):
        for e in macaulay_manifest[group]:
            path = Path(e["local"])
            sha1, sha256, size = digests(path)
            entry_id = unique(slug(e["assetId"]))
            code = e.get("licenseId", "")
            mapped = MACAULAY.get(code)
            licence_name = mapped[1] if mapped else e.get("license", code)
            allowed, canonical, reason = classify_entry(licence_name, "")
            # A permitted class with no published version is blocked, not refused: it
            # becomes usable the moment the version is recorded from a written source.
            # The gate refuses it today because a credit cannot name an unknown licence.
            if code == "LICENSE5":
                allowed, canonical, reason = True, None, None
            version_known = bool(mapped and mapped[2] and canonical in ("cc0", "public-domain"))
            needs: list[str] = []
            label = macaulay_label(e.get("tags"))
            if label is None:
                needs.append(
                    "record the song/call label: the asset carries no functional tag, so a "
                    "song or call claim has nothing to cite"
                )
            if allowed and not version_known:
                needs.append(
                    "record the licence version from a deed or written confirmation: the "
                    "archive publishes the class (" + code + ") and never the version, so the "
                    "attribution cannot name the licence it is made under"
                )
            if not e.get("recordist"):
                needs.append("record the recordist from the asset page")
            if not e.get("sourceUrl"):
                needs.append("record the asset page URL")
            entries.append({
                "id": entry_id,
                "auditionId": None,
                "recordingId": entry_id,
                "library": "Macaulay Library (Cornell Lab of Ornithology)",
                "title": e["assetId"],
                "sourceUrl": e.get("sourceUrl"),
                "fileUrl": "https://cdn.download.ams.birds.cornell.edu/api/v2/asset/"
                           + e["assetId"].removeprefix("ML") + "/mp3",
                "recordist": e.get("recordist") or None,
                "label": label,
                "licence": {
                    "asPublished": e.get("license"),
                    "id": canonical,
                    "family": mapped[0] if mapped else family_of(canonical),
                    "code": code,
                    "deed": None,
                    "versionVerified": version_known,
                    "howVerified": mapped[2] if (mapped and mapped[2]) else None,
                },
                "status": "refused" if not allowed else ("blocked" if needs else "ready"),
                "reason": None if allowed else reason,
                "verification": {
                    "sha1": sha1,
                    "sha1MatchesPublished": None,
                    "sha256": sha256,
                    "hashBasis": "first download on this host (the archive publishes no digest)",
                    "checkedOn": "2026-11-23",
                    "needs": needs,
                },
                "storage": {
                    "master": str(path.relative_to(corpus)),
                    "bytes": size,
                    "durationSeconds": duration(path),
                },
            })

    entries.sort(key=lambda x: (0 if x["auditionId"] else 1,
                                int(x["auditionId"][1:]) if x["auditionId"] else 0,
                                x["id"]))

    # derivatives: audition cuts, the ear-review copies, and the shipped clip
    derivatives: list[dict] = []
    for e in audition:
        path = Path(e["auditionFile"])
        if not path.exists():
            continue
        _, sha256, size = digests(path)
        source = next(x for x in entries if x["storage"]["master"] == str(
            Path(e["local"]).relative_to(corpus)))
        derivatives.append({
            "id": e["auditionId"],
            "kind": "audition-cut",
            "sourceId": source["id"],
            "licence": source["licence"]["id"],
            "storage": {"path": str(path.relative_to(corpus)), "bytes": size,
                        "fromSeconds": e.get("auditionFrom"),
                        "durationSeconds": e.get("auditionLength")},
            "sha256": sha256,
        })

    for clip in sorted((corpus / "candidates").glob("*.mp3")):
        m = re.search(r"xc(\d+)", clip.name)
        source = next((x for x in entries if m and x["recordingId"] == "xc" + m.group(1)), None)
        if source is None:
            continue
        _, sha256, size = digests(clip)
        derivatives.append({
            "id": unique(slug(clip.stem)),
            "kind": "ear-review-cut",
            "sourceId": source["id"],
            "licence": source["licence"]["id"],
            "note": "byte-identical copy handed over in ~/birdie-review for the ear pass; "
                    "the corpus copy is the one this ledger tracks",
            "storage": {"path": str(clip.relative_to(corpus)), "bytes": size},
            "sha256": sha256,
        })

    shipped = REPO / "web" / "public" / "audio" / "american-robin" / "pillar-carol-01.mp3"
    _, sha256, size = digests(shipped)
    shipped_check = {
        "id": "pillar-carol-01",
        "kind": "shipped-clip",
        "sourceId": next(x["id"] for x in entries if x["recordingId"] == "xc570791"),
        "licence": "cc-by-sa-4.0",
        "storage": {"path": "web/public/audio/american-robin/pillar-carol-01.mp3",
                    "bytes": size, "fromSeconds": 0, "durationSeconds": 10.04},
        "sha256": sha256,
    }
    # The species verdict is bound to the clip's digest: a rebuilt clip cannot
    # inherit the old check. `check` fails if this is missing or stale.
    recorded = species_checks().get("pillar-carol-01")
    if recorded:
        shipped_check["speciesCheck"] = recorded
    derivatives.append(shipped_check)

    return {
        "version": 1,
        "generated": "2026-11-23",
        "why": (
            "A recording is usable only if the file we hold can be traced to a source page "
            "that names the recordist, the licence, and what the archive labels the sound. "
            "A clip that ships also carries a BirdNET species verdict bound to its digest. "
            "The masters live outside git "
            "(~/projects/birdie-curation, ~75 MB); this ledger is the versioned part, so the "
            "provenance cannot be lost with the disk. It is not a licence grant: the grant is "
            "the deed at the source page, and `verification.needs` lists what has not been "
            "checked. A file with a permitted licence but an unverified field is `blocked`, "
            "not usable."
        ),
        "policy": "web/src/species/licence-policy.json",
        "corpusRoot": str(corpus),
        "rebuild": "python3 tools/curation/sources.py --write",
        "states": {
            "ready": "permitted licence, the archive's or recordist's song/call label, and recordist, source page, licence version (or PD basis) and digest are recorded",
            "blocked": "permitted licence family, but a named field is missing; the file cannot be used until it is supplied",
            "refused": "not permitted, unrecognised, or published without a mapping; unusable short of written permission",
        },
        "entries": entries,
        "derivatives": derivatives,
    }


def table(ledger: dict) -> str:
    rows = ["| file | type | library | licence | status | what is needed before use |",
            "|---|---|---|---|---|---|"]
    for e in ledger["entries"]:
        lic = e["licence"]["id"] or e["licence"]["asPublished"]
        if e["licence"].get("code") and not e["licence"]["versionVerified"]:
            lic += f" ({e['licence']['code']}, no version)"
        need = "; ".join(e["verification"]["needs"]) or (
            "none — credit recorded" if e["licence"]["id"] not in ("cc0", "public-domain")
            else "none — no attribution required")
        if e["status"] == "refused":
            need = e.get("reason") or "not permitted"
        label = e["title"] if e["library"].startswith("Macaulay") else (
            e.get("auditionId") or e["title"].replace("File:", ""))
        kind = "—"
        if e.get("label"):
            kind = e["label"]["verdict"] + (
                " (tag)" if e["label"]["basis"] == "archive-tag" else " (Type)")
        rows.append(f"| {label} | {kind} | {e['library'].split(' (')[0]} | {lic} | "
                    f"{e['status']} | {need} |")
    return "\n".join(rows)


def write(corpus: Path) -> int:
    ledger = build(corpus)
    LEDGER.write_text(json.dumps(ledger, indent=1, ensure_ascii=False) + "\n")
    counts = {}
    for e in ledger["entries"]:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    print(f"wrote {LEDGER.relative_to(REPO)}: {len(ledger['entries'])} files "
          f"({counts.get('ready', 0)} ready, {counts.get('blocked', 0)} blocked, "
          f"{counts.get('refused', 0)} refused), {len(ledger['derivatives'])} derivatives")
    return 0


def check(corpus: Path) -> int:
    ledger = json.loads(LEDGER.read_text())
    failures: list[str] = []
    by_id = {e["id"]: e for e in ledger["entries"]}
    seen_masters: set[str] = set()

    for e in ledger["entries"]:
        path = corpus / e["storage"]["master"]
        seen_masters.add(e["storage"]["master"])
        if not path.exists():
            failures.append(f"{e['id']}: master missing at {path}")
            continue
        sha1, sha256, size = digests(path)
        if sha256 != e["verification"]["sha256"]:
            failures.append(f"{e['id']}: sha256 changed since the ledger was written")
        if size != e["storage"]["bytes"]:
            failures.append(f"{e['id']}: size changed since the ledger was written")
        if e["licence"]["id"] is None and e["status"] not in ("refused", "blocked"):
            failures.append(f"{e['id']}: {e['status']} entry with no canonical licence")
        if e["status"] == "ready":
            if not e["recordist"]:
                failures.append(f"{e['id']}: ready but no recordist")
            if not e.get("label") or not e["label"].get("verdict"):
                failures.append(f"{e['id']}: ready but no song/call label")
            if not e["sourceUrl"]:
                failures.append(f"{e['id']}: ready but no source page")
            if e["verification"]["needs"]:
                failures.append(f"{e['id']}: ready but needs {e['verification']['needs']}")
            if e["verification"]["sha1MatchesPublished"] is False:
                failures.append(f"{e['id']}: ready but local file does not match published SHA1")
        if e["status"] == "blocked" and not e["verification"]["needs"]:
            failures.append(f"{e['id']}: blocked but nothing is listed as needed")
        if e["status"] == "refused" and not e.get("reason"):
            failures.append(f"{e['id']}: refused without a reason")

    for d in ledger["derivatives"]:
        src = by_id.get(d["sourceId"])
        if src is None:
            failures.append(f"{d['id']}: derivative of unknown source {d['sourceId']}")
            continue
        if src["status"] == "refused":
            failures.append(f"{d['id']}: derivative of refused source {src['id']}")
        # A shipped clip is a song variant in a record. The ledger has to be able to
        # back that claim with a published label, or the record is asserting a type
        # the corpus does not document.
        if d["kind"] == "shipped-clip":
            verdict = (src.get("label") or {}).get("verdict") or ""
            if "song" not in verdict:
                failures.append(
                    f"{d['id']}: shipped clip's source {src['id']} has no song label"
                )
            sc = species_checks().get(d["id"])
            if not sc:
                failures.append(f"{d['id']}: no recorded species check")
            else:
                if sc.get("sha256") != d["sha256"]:
                    failures.append(
                        f"{d['id']}: species check is bound to a different file"
                    )
                if sc.get("verdict") != "pass":
                    failures.append(
                        f"{d['id']}: species check verdict is {sc.get('verdict')}"
                    )
                if d.get("speciesCheck") != sc:
                    failures.append(
                        f"{d['id']}: ledger's species check is stale (run --write)"
                    )
        if src["licence"]["id"] and d["licence"] != src["licence"]["id"]:
            if not (src["licence"]["id"].startswith("cc-by-sa")
                    and d["licence"].startswith("cc-by-sa")):
                failures.append(f"{d['id']}: licence {d['licence']} does not match source {src['licence']['id']}")
        path = Path(d["storage"]["path"])
        if not path.is_absolute():
            path = REPO / path
        if path.exists():
            _, sha256, _ = digests(path)
            if sha256 != d["sha256"]:
                failures.append(f"{d['id']}: derivative bytes changed")

    # No orphan audio: every file under the corpus and in the bundle must be accounted for.
    ledger_paths = set(seen_masters) | {d["storage"]["path"] for d in ledger["derivatives"]}
    for p in sorted(corpus.rglob("*")):
        if p.suffix.lower() not in (".mp3", ".ogg", ".wav", ".flac"):
            continue
        rel = str(p.relative_to(corpus))
        if rel not in ledger_paths:
            failures.append(f"orphan audio in corpus: {rel}")
    for p in sorted((REPO / "web" / "public" / "audio").rglob("*")):
        if p.suffix.lower() not in (".mp3", ".ogg", ".wav", ".flac"):
            continue
        rel = str(p.relative_to(REPO))
        if rel not in ledger_paths:
            failures.append(f"orphan audio in bundle: {rel}")

    # The doc embeds a generated table; a stale table is the failure mode #6 exists for.
    if DOC.exists():
        text = DOC.read_text()
        if TABLE_BEGIN in text and TABLE_END in text:
            embedded = text.split(TABLE_BEGIN, 1)[1].split(TABLE_END, 1)[0].strip("\n")
            if embedded.strip() != table(ledger).strip():
                failures.append("docs/curation/american-robin-audio.md: source table is stale "
                                "(run --write then paste --table)")

    for f in failures:
        print("FAIL", f)
    print(f"checked {len(ledger['entries'])} files and {len(ledger['derivatives'])} derivatives: "
          f"{len(failures)} failure(s)")
    return 1 if failures else 0


def report(corpus: Path) -> int:
    ledger = json.loads(LEDGER.read_text())
    order = {"ready": 0, "blocked": 1, "refused": 2}
    for e in sorted(ledger["entries"], key=lambda x: order[x["status"]]):
        print(f"{e['status']:8} {e['id']:26} {str(e['licence']['id']):14} {e['sourceUrl'] or ''}")
        for need in e["verification"]["needs"]:
            print(f"         - {need}")
        if e.get("reason"):
            print(f"         - {e['reason']}")
    counts = {}
    for e in ledger["entries"]:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    print("\n" + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Build and audit the audio provenance ledger.")
    ap.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="rebuild the ledger")
    g.add_argument("--check", action="store_true", help="audit ledger, files and doc table")
    g.add_argument("--report", action="store_true", help="per-file status and outstanding work")
    g.add_argument("--table", action="store_true", help="print the markdown table for the doc")
    a = ap.parse_args()
    if a.write:
        return write(a.corpus)
    if a.check:
        return check(a.corpus)
    if a.report:
        return report(a.corpus)
    print(table(json.loads(LEDGER.read_text())))
    return 0


